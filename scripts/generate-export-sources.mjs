/* Auto-generates the browser-side source catalogue used by standalone ZIP export.
   Keeping this list close to the renderer makes preview/export parity explicit. */
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import path from "node:path";

const root = process.cwd();
const files = [
  "src/website/WebsiteRenderer.tsx",
  "src/website/renderer.tsx",
  "src/website/sections/SectionRenderer.tsx",
  "src/website/sections/Global.tsx",
  "src/website/sections/Hero.tsx",
  "src/website/sections/Content.tsx",
  "src/website/sections/Restaurant.tsx",
  "src/website/sections/Business.tsx",
  "src/website/sections/Portfolio.tsx",
  "src/website/sections/Conversion.tsx",
  "src/website/sections/Ecommerce.tsx",
  "src/features/sections/registry.ts",
  "src/data/palette.ts",
  "src/data/fonts.ts",
  "src/components/ui/ui.tsx",
  "src/utils/helpers.ts",
  "src/types/theme.ts",
  "src/types/sections.ts",
  "src/types/project.ts",
];

const sources = Object.fromEntries(files.map((file) => [file, readFileSync(path.join(root, file), "utf8")]));
const output = path.join(root, "src/features/export/generatedSources.ts");
mkdirSync(path.dirname(output), { recursive: true });
writeFileSync(
  output,
  `/* AUTO-GENERATED by scripts/generate-export-sources.mjs — do not edit. */\n` +
    `export const STANDALONE_SOURCES: Readonly<Record<string, string>> = ${JSON.stringify(sources, null, 2)};\n`
);
console.log(`✓ Export source catalogue generated (${files.length} files)`);
